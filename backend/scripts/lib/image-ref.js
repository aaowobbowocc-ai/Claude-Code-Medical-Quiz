/**
 * 第二次踩同一個坑（2026-09-24）：這份名單認不得「圖 2 是…」「圖3中…」「表 1 是…」
 * 這種**編號式**的寫法，於是學測／分科的 471 題（「圖 2 是明清時期…廟宇分布圖」
 * 「圖3中相鄰兩條等高線間的高度差為何？」）從來沒被列為補圖候選。
 *
 * 加上「圖/表 緊接編號」這一條。要求緊接數字或中文數字，才不會把
 * 「圖書館」「表示」「表現」掃進來。表格題若原卷是純文字排版，
 * 補圖工具自己的「該區塊是空白」檢查會擋掉，不必在這裡先排除。
 *
 * 2026-11-02：中文數字那一條會把「量詞」當成編號 ——
 *   「發**表一**個定律」「代**表一**定的意義」「近視力**表一般**放置」
 *   「心電**圖二個**連續 QRS 波」「代**表一**個國家」
 * 中文數字後面接量詞／副詞時就不是編號。負向前瞻原本只排除「幾成倍分」，
 * 補上常見的量詞與副詞起首字。全站因此少報 9 筆誤判，
 * 而**已經有圖、且唯一證據是這一條的題有 0 筆**被影響（改前實測過）。
 *
 * 2026-11-11：阿拉伯數字那一條**完全沒有護欄**，於是這些全被當成圖號：
 *   「症狀檢核**表90**-修訂版（SCL-90-R）」「E 字視力**表20**／20 視標」
 *   （⚠️ 上面那個斜線一定要用全形：半形的「**／」會把這個區塊註解提早關掉）
 *   「萬國視力**表0**.5」「代**表4**-hydroxyproline」「距地**表720** 公里」
 * 真的圖號後面不會再接數字、小數點、連字號或斜線。改成
 * 「一到兩位數，且後面不是 0-9 . ． - /」。
 *
 * 同一輪再補四條，每條都是**固定詞組**，不是看形狀猜的：
 *   ·「**意圖為**自己或第三人不法之利益」—— 刑法背信罪的條文，不是「圖為…」
 *   ·「**家族圖譜**(genograms)」—— 諮商技術的名稱
 *   ·「**圖示方式**／**圖示表**徵／**圖示、**表格對照」—— 當動詞用，不是卷上有圖
 *     ⚠️ 不能連「圖示，」一起排除：「承上題圖示，請問…」「依圖示，齒槽嵴…」
 *       那種是真的有圖，第一版把「，」寫進去就誤殺了 13 題。
 *   · 中文數字的量詞名單補上「版組項世軸歲」——「量**表五版**」「X n **表一組**」
 *     「發**表六項**」「心電**圖六軸**系統」「代**表二十一世**紀」「量**表 四歲**兒童」
 *
 * 全站少報 29 筆誤判、**一筆都沒有多抓**。受影響的「本來就有圖」只有 3 筆，
 * 而且三筆都是本來就不該命中的（地表720、量表 四歲、圖示表達）——
 * 它們有圖是因為別的原因，不是因為題幹指名了圖。
 *
 * 2026-11-12：編號那兩條還是會把「名詞＋數字」當成圖號。這次不是逐例補，
 * 而是補一條**前綴黑名單**（允許中間有空白，「肌電 圖 4抹片」才擋得到）：
 *   代表1% 代表2 cc 代表40% 代表95% 代表6個 代表一種 / 量表20 量表30 量表13 量表60
 *   檢核表90 / 附表四之一 / 發表一篇 發表 50年 / 結存表46 計算表36 付息表36 盈虧表37
 *   地表720 角膜地圖為 / 體表20 體表 3～4 mm / 每張圖為1920 / 溝通意圖 2 歲
 *   肌電 圖 4 心電圖 24 / 全省圖14張 / 藥圖二十五卷 / 視力表四公尺 / 對照表 六大類
 *   平衡表 24 小時 / 散肌表八風
 * 反過來，**真的圖號前面是動詞或介詞**（利用表3、去到圖1、做成圖四、位居圖5、
 * 調整圖2、採取圖7、取得表5、記錄於表三…），所以不能改成「前面是中文字就不算」
 * ——那條試過，一口氣誤殺 28 題真的有圖的（2026-11-12 實測）。
 *
 * 同一輪還補了：
 *   ·「右圖／左圖」—— 台電卷寫「如右【圖1】」、中醫一階寫「右圖藥材的敘述」，
 *     43 題從來沒被列為候選（其中 24 題其實早就有圖了，是這份名單不認得）。
 *   ·「圖為」前面是「張／地」時不算（每張圖為1920×1080、角膜地圖為最佳）。
 *   · 中文數字的量詞名單補「種卷」——「下表三種治療方式」「藥圖二十五卷」。
 *
 * 全站少報 49 筆誤判、新增 43 筆（19 筆是真的還缺圖）。
 * 受影響的「本來就有圖」只有 1 筆（全省圖14張），而且它本來就不該命中。
 */
const NOT_FIGNO = '(?<![代量核附發存算息虧地體張意肌省藥膜力照衡電課時]\\s*)';
const FIG_QUANT = '一二三四五六七八九十幾成倍分定個些切般直樣連致旦起再向次點面層類年天步版組項世軸歲種卷';
const IMAGE_REF = new RegExp(
  '附圖|如圖|圖示(?![方表、])|[下上左右]圖|圖中|(?<![意張地])圖為|如下圖|如上圖|根據圖|見圖|圖所示|下列圖|示意圖|'
  + '箭頭所指|箭頭|(?<!家族)圖譜|血球如|此圖|箭號|'
  + NOT_FIGNO + '[圖表]\\s*[0-9０-９]{1,2}(?![0-9０-９．.\\-/／])|'
  + NOT_FIGNO + '[圖表]\\s*[一二三四五六七八九十]{1,3}(?![' + FIG_QUANT + '])');

/** 題幹＋選項一起看：有些卷把圖放在選項裡。 */
function needsImage(q) {
  const txt = (q.question || '') + ' ' + Object.values(q.options || {}).join(' ');
  return IMAGE_REF.test(txt);
}

module.exports = { IMAGE_REF, needsImage };
