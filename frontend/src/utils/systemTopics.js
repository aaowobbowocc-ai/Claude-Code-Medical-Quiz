export function classifySystem(q) {
  const text = `${q?.question || ''} ${q?.subject_name || ''} ${q?.subject || ''} ${Object.values(q?.options || {}).join(' ')}`
  let best = null, bestScore = 0
  for (const s of SYSTEMS) {
    let score = 0
    for (const w of s.kw) if (text.includes(w)) score++
    if (score > bestScore) { bestScore = score; best = s }
  }
  return best && bestScore > 0 ? best : null
}

export function systemColor(key) {
  return SYSTEMS.find(s => s.key === key)?.color || '#94A3B8'
}
