/**
 * 大考中心（學測／分科）選項尾巴的卷面殘渣清單。
 *
 * PDF 的文字層會把下一題的題組說明、頁碼、節次標題、圖號一路吐在最後一個
 * 選項後面。從 PDF 重建選項的腳本都會踩到同一批殘渣，所以清單放這裡共用，
 * 不要各自抄一份——抄過去的那份一定比較短，會漏掉別人已經踩過的坑
 * （repair-ceec-missing-fifth.js 第一版就是這樣讓「11-12 題為題組 如圖5 所示…」
 *  整段跟著選項 E 一起進題庫）。
 *
 * ⚠️ 這裡只收**明確標記**。試過兩條「看形狀」的規則，兩條都把好選項切壞了：
 *   · 「連續 4 組以上的數字當座標軸」→ 109 學測自然 #58 的「1.0×10⁻⁶ M」被削掉，
 *     四個選項變成兩兩重複；108 社會 #57 的「1707、1800 年的聯合法」也不見了。
 *   · 「同一段重複出現就切」→ 106 國文 #13 的「孔乙己還欠十九個錢呢！」原文就是
 *     講兩次；114 地理 #40 的「減去平日日間活動人數的欄位數值」也是。
 * 圖表座標軸的文字就留著，寧可少修（見 procedure_health_report_rules）。
 */
const JUNK = [
  /\s*\d{2,3}\s*年\s*(分科|學測)/,          // 111 年分科 / 110 年學測
  /\s*第\s*\d+\s*頁/,
  /\s*共\s*\d+\s*頁/,
  /\s*[-－]\s*\d+\s*[-－]\s*$/,
  /\s*[一二三四五六]\s*、\s*(單|多)選題/,
  /\s*第\s*[壹貳參肆]\s*部分/,
  /\s*說明\s*[：:︰]/,
  /\s*（\s*占\s*\d+\s*分\s*）/,
  /\s*\d+\s*[-－~～至]\s*\d+\s*題?\s*為題組/,
  /\s*第\s*\d+\s*題至第\s*\d+\s*題/,
  /\s*請記得在答題卷/,
  // 圖號／表號只在**尾巴**才算殘渣，而且後面不能接「所示/中/的/之」
  //（「如圖7所示」是選項正文的一部分，切了就把句子砍斷）
  /\s+[圖表]\s*[一二三四五六\d]+\s*(?![所中的之])/,
];

/** 從第一個命中的殘渣切掉。index 為 0 時不切——整段都是殘渣多半是比對出錯。 */
function cleanTail(t) {
  let out = String(t);
  for (const re of JUNK) {
    const m = re.exec(out);
    if (m && m.index > 0) out = out.slice(0, m.index);
  }
  return out.trim();
}

module.exports = { JUNK, cleanTail };
