/**
 * 「這題需要看圖」的判定 —— 單一來源。
 *
 * 為什麼收斂：scan-image-deps.js 與 add-missing-images.js 各寫了一份 regex，
 * 兩份不一樣：盤點用的那份認得「下列圖」「示意圖」「箭頭所指」，補圖用的那份不認。
 * 結果是「盤點說 rt 缺 75 題，補圖工具卻回報 0 個候選」——工具沒壞，只是兩張名單不同。
 * （2026-09-15：rt 102020「下列圖形顯示病人使用的通氣模式為何？」整批漏掉的原因）
 */

/**
 * 第二次踩同一個坑（2026-09-24）：這份名單認不得「圖 2 是…」「圖3中…」「表 1 是…」
 * 這種**編號式**的寫法，於是學測／分科的 471 題（「圖 2 是明清時期…廟宇分布圖」
 * 「圖3中相鄰兩條等高線間的高度差為何？」）從來沒被列為補圖候選。
 *
 * 加上「圖/表 緊接編號」這一條。要求緊接數字或中文數字，才不會把
 * 「圖書館」「表示」「表現」掃進來。表格題若原卷是純文字排版，
 * 補圖工具自己的「該區塊是空白」檢查會擋掉，不必在這裡先排除。
 */
const IMAGE_REF = /附圖|如圖|圖示|下圖|上圖|圖中|圖為|如下圖|如上圖|根據圖|見圖|圖所示|下列圖|示意圖|箭頭所指|箭頭|圖譜|血球如|此圖|箭號|[圖表]\s*[0-9０-９]|[圖表]\s*[一二三四五六七八九十]{1,3}(?![幾成倍分])/;

/** 題幹＋選項一起看：有些卷把圖放在選項裡。 */
function needsImage(q) {
  const txt = (q.question || '') + ' ' + Object.values(q.options || {}).join(' ');
  return IMAGE_REF.test(txt);
}

module.exports = { IMAGE_REF, needsImage };
